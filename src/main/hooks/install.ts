import { chmod, mkdir, writeFile } from 'node:fs/promises'
import { rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { HOOK_EVENTS } from '../../shared/hooks'
import { grokHome } from '../store/paths'

/**
 * macOS caps `sockaddr_un.sun_path` at 104 bytes. Exceeding it fails with a
 * truncated address rather than a clear error, so stay well clear.
 */
const MAX_SOCKET_PATH = 100

export const HOOK_FILE_NAME = 'asv-agent-desk.json'
export const HOOK_SCRIPT_NAME = 'asv-agent-desk-emit.sh'

export function hooksDir(root = grokHome()): string {
  return join(root, 'hooks')
}

export function hookFilePath(root = grokHome()): string {
  return join(hooksDir(root), HOOK_FILE_NAME)
}

export function hookScriptPath(root = grokHome()): string {
  return join(hooksDir(root), HOOK_SCRIPT_NAME)
}

/**
 * Socket lives in the temp dir, not the home directory.
 *
 * A standard macOS `$TMPDIR` yields roughly 62 bytes, comfortably inside the
 * limit. A custom or unusually deep `TMPDIR` could still overflow it, so fall
 * back to `/tmp` — always short, and the socket is transient anyway.
 */
export function socketPath(tmp = tmpdir()): string {
  const preferred = join(tmp, 'asv-agent-desk.sock')
  if (Buffer.byteLength(preferred, 'utf8') <= MAX_SOCKET_PATH) return preferred
  return '/tmp/asv-agent-desk.sock'
}

/** Single-quote for `sh`, escaping any embedded quote. */
function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`
}

/**
 * The shell script Grok runs for every event.
 *
 * Grok hands the event JSON on stdin, so this just forwards it to the socket
 * and gets out of the way:
 *
 * - `--max-time 2` bounds the whole thing well inside Grok's hook timeout.
 * - stdout and stderr are discarded so nothing pollutes the agent's output.
 * - `exit 0` unconditionally. Passive hooks have no business reporting
 *   failure, and a non-zero exit would show as a failed hook run in the TUI
 *   just because ASV Agent Desk happened to be closed.
 */
export function buildHookScript(sock: string): string {
  return `#!/bin/sh
# Generated by ASV Agent Desk. Forwards Grok hook events to the running app.
# Safe to delete: ASV Agent Desk rewrites it on launch and removes it on quit.
curl -s -S --max-time 2 --unix-socket ${shellQuote(sock)} \\
  -X POST -H 'content-type: application/json' --data-binary @- \\
  http://localhost/e >/dev/null 2>&1
exit 0
`
}

/**
 * The config Grok reads. Every event runs the same script.
 *
 * `command` rather than `http`: Grok 0.2.103 blocks `http://` hook URLs under
 * an SSRF policy and only accepts `https://`, so a loopback HTTP endpoint is
 * never contacted. A command hook has no such restriction.
 */
export function buildHookConfig(script: string): unknown {
  return {
    hooks: Object.fromEntries(
      HOOK_EVENTS.map((event) => [
        event,
        [{ hooks: [{ type: 'command', command: script, timeout: 3 }] }],
      ]),
    ),
  }
}

/**
 * Register ASV Agent Desk as a personal hook.
 *
 * Personal (`~/.grok/hooks`) rather than project (`<project>/.grok/hooks`) on
 * purpose: project hooks require explicit trust via `/hooks-trust` before they
 * run, which would mean the rail silently showed nothing in every new repo.
 */
export async function installHooks(sock: string, root = grokHome()): Promise<string> {
  const dir = hooksDir(root)
  await mkdir(dir, { recursive: true })

  const script = join(dir, HOOK_SCRIPT_NAME)
  await writeFile(script, buildHookScript(sock), 'utf8')
  await chmod(script, 0o755)

  const config = join(dir, HOOK_FILE_NAME)
  await writeFile(config, JSON.stringify(buildHookConfig(script), null, 2), 'utf8')
  return config
}

/**
 * Leave nothing behind pointing at a socket that no longer exists.
 *
 * Deliberately synchronous. This runs from Electron's `before-quit`, which
 * does not wait for promises — an async version removed the config but left
 * the script behind, because the process exited between the two awaits.
 */
export function uninstallHooks(root = grokHome()): void {
  rmSync(hookFilePath(root), { force: true })
  rmSync(hookScriptPath(root), { force: true })
}
